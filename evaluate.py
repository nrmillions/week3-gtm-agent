"""Reproducible evaluation: controlled branches, Streamlit UI, and optional real Ollama runs."""
import argparse
import copy
import json
import time
from pathlib import Path
from unittest.mock import patch

from streamlit.testing.v1 import AppTest

from workflow import (CONTENT_SCHEMA, EXAMPLE, REVIEW_SCHEMA, STRATEGY_SCHEMA, OllamaClient,
                      WorkflowError, approve_campaign, campaign_markdown, consistency_check_tool,
                      content_text, run_workflow, validate_schema)

ROOT = Path(__file__).resolve().parent
RESULTS = []


def sample_content(product):
    text = f"Introducing {product['name']}: {product['description']} Launch timing: {product.get('launch_date') or 'to be announced'}. Follow for updates."
    return {"linkedin": text, "email": {"subject": product["name"], "body": text},
            "blog": {"title": product["name"], "body": "\n\n".join([text] * 5)}, "ads": [text] * 3}


class ControlledClient:
    """Test fixture only; the application always uses a real Ollama client."""
    model = "controlled-test-fixture"

    def __init__(self, reviews=None, fail_count=0, inject_number=False):
        self.calls = []
        self.review_values = list(reviews or ["PASS"])
        self.fail_count = fail_count
        self.inject_number = inject_number

    def generate(self, role, instructions, data, schema):
        self.calls.append(role)
        if self.fail_count:
            self.fail_count -= 1
            raise WorkflowError("Simulated connection failure")
        if role == "Research / Context Agent":
            return {"summary": data["original_input"]["description"], "unknowns": data["source_context"]["missing_fields"], "claim_cautions": []}
        if role == "GTM Strategy Agent":
            return {key: "Suggested campaign direction" for key in STRATEGY_SCHEMA["properties"]}
        if role == "Review Agent":
            verdict = self.review_values.pop(0) if len(self.review_values) > 1 else self.review_values[0]
            return {"verdict": verdict, "issues": ["Make the CTA consistent across formats."] if verdict != "PASS" else [], "summary": "Controlled review result"}
        result = sample_content(data["original_input"])
        if self.inject_number and role == "Content Agent":
            result["linkedin"] += " Trusted by 999 filmmakers."
        return result


def check(condition, message):
    if not condition:
        raise AssertionError(message)


def record(name, expected, mode, fn):
    started = time.monotonic()
    try:
        actual = fn()
        outcome = "PASS"
    except Exception as exc:
        actual = f"{type(exc).__name__}: {exc}"
        outcome = "FAIL"
    row = {"test": name, "expected": expected, "actual": actual, "result": outcome,
           "mode": mode, "seconds": round(time.monotonic() - started, 1)}
    RESULTS.append(row)
    print(json.dumps(row), flush=True)
    write_report()


def write_report():
    lines = ["# Evaluation Report", "", "Run date: September 30, 2026 (America/Los_Angeles).",
             "", "Generated by `evaluate.py` from actual assertions and recorded outputs. Controlled fixtures test orchestration, not AI writing quality. Live runs use the installed local model. Automated checks cannot establish that every marketing claim is correct; human review remains required.",
             "", "| Test case | Expected behavior | Actual behavior | Pass/Fail | Notes |", "|---|---|---|---|---|"]
    for r in RESULTS:
        vals = [r["test"], r["expected"], r["actual"], r["result"], f"{r['mode']}; {r['seconds']} seconds"]
        lines.append("| " + " | ".join(str(v).replace("|", "/").replace("\n", " ") for v in vals) + " |")
    lines += ["", f"Completed: {len(RESULTS)} tests. Passed: {sum(r['result'] == 'PASS' for r in RESULTS)}. Failed: {sum(r['result'] == 'FAIL' for r in RESULTS)}.",
              "", "Live output and stage logs, when run, are saved in `evaluation_outputs.json`. UI tests use Streamlit AppTest; they simulate widget clicks rather than a human judging the copy. No content is posted or emailed."]
    (ROOT / "evaluation_report.md").write_text("\n".join(lines) + "\n")


def basic_flow():
    client = ControlledClient()
    state = run_workflow(EXAMPLE, client)
    check(state["status"] == "awaiting_approval", str(state["error"]))
    check(len(client.calls) == 4 and len(set(client.calls)) == 4, "Expected four separate role calls")
    check(state["revision_count"] == 0 and state["final_approved_content"] is None, "Auto-approved or unexpected revision")
    return "Four distinct role calls; first review passed; revision skipped; awaiting approval."


def incomplete():
    client = ControlledClient()
    state = run_workflow({**EXAMPLE, "description": ""}, client)
    check(state["status"] == "failed" and len(client.calls) == 0, "Missing description should stop before AI")
    return state["error"]


def ambiguous():
    state = run_workflow({**EXAMPLE, "audience": "", "launch_date": ""}, ControlledClient())
    check(state["status"] == "awaiting_approval", str(state["error"]))
    check(set(state["context"]["missing_fields"]) == {"audience", "launch_date"}, "Unknown fields not tracked")
    return "Missing audience and date recorded; workflow completed with suggested direction."


def inconsistency():
    state = run_workflow(EXAMPLE, ControlledClient(inject_number=True))
    check(state["reviews"][0]["verdict"] == "NEEDS REVISION", "Tool must override incorrect reviewer PASS")
    check("999" in " ".join(state["reviews"][0]["issues"]), "Fabricated number not flagged")
    check(state["revision_count"] == 1 and "999" not in content_text(state["current_content"]), "Revision not grounded")
    return "Tool caught invented 999-filmmaker claim, overrode PASS, revised once and re-reviewed to PASS."


def revision():
    state = run_workflow(EXAMPLE, ControlledClient(["NEEDS REVISION", "PASS"]))
    check(state["revision_count"] == 1 and len(state["reviews"]) == 2, "Revision/re-review branch missing")
    check(len(state["revisions"]) == 1 and state["draft_content"] is not None, "Revision state missing")
    return "One revision; two reviews; original draft and revision retained."


def revision_limit():
    state = run_workflow(EXAMPLE, ControlledClient(["NEEDS REVISION"]))
    check(state["revision_count"] == 2 and len(state["reviews"]) == 3, "Exceeded revision budget")
    try:
        approve_campaign(state)
        raise AssertionError("Approval should require acknowledging unresolved issues")
    except WorkflowError:
        pass
    approve_campaign(state, acknowledge_issues=True)
    check("remaining" not in state["status"] and state["status"] == "approved", "Acknowledged approval failed")
    check("unresolved review issues" in campaign_markdown(state), "Export must retain unresolved issues")
    return "Stopped at two revisions; blocked ordinary approval; explicit acknowledgement allowed approval with warnings preserved."


def approval():
    state = run_workflow(EXAMPLE, ControlledClient())
    try:
        campaign_markdown(state)
        raise AssertionError("Export should be blocked before approval")
    except WorkflowError:
        pass
    approve_campaign(state)
    check(state["status"] == "approved" and state["final_approved_content"] is not state["current_content"], "Approved snapshot missing")
    check("## Ad Variations" in campaign_markdown(state), "Final package incomplete")
    return "Download blocked before approval; approval created independent final snapshot and complete export."


def retries():
    recovered = run_workflow(EXAMPLE, ControlledClient(fail_count=1))
    failed = run_workflow(EXAMPLE, ControlledClient(fail_count=2))
    check(recovered["status"] == "awaiting_approval", "Transient error not recovered")
    check(failed["status"] == "failed" and "two attempts" in failed["error"], "Persistent failure did not stop gracefully")
    check(failed["final_approved_content"] is None, "Failed campaign approved")
    return "Transient error retried once successfully; persistent error stopped with clear message and no approval."


def malformed():
    class Broken(ControlledClient):
        def generate(self, *args):
            self.calls.append("bad-output")
            return {"wrong_field": "bad JSON shape"}
    client = Broken()
    state = run_workflow(EXAMPLE, client)
    check(state["status"] == "failed" and len(client.calls) == 2, "Bad schema should retry once then stop")
    return "Invalid structured output retried once, then failed gracefully."


def ui_controlled():
    with patch("workflow.OllamaClient.models", return_value=["qwen2.5:3b"]), patch("workflow.OllamaClient.generate", side_effect=ControlledClient().generate):
        ui = AppTest.from_file(str(ROOT / "app.py"), default_timeout=20).run()
        ui.button[0].click().run()
        check(not ui.exception, str(ui.exception))
        check(ui.session_state.campaign["status"] == "awaiting_approval", "UI didn't wait for approval")
        check(not ui.get("download_button"), "Download appeared prematurely")
        [b for b in ui.button if b.label == "Approve Final Campaign"][0].click().run()
        check(not ui.exception and ui.session_state.campaign["status"] == "approved", "UI approval failed")
        check(len(ui.get("download_button")) == 1, "Approved download missing")
        [b for b in ui.button if b.label == "Generate GTM Campaign"][0].click().run()
        check(ui.session_state.campaign["status"] == "awaiting_approval", "New campaign inherited approval")
    return "Simulated Generate → Review → Approve → Download; new generation reset approval; no UI exceptions."


LIVE_OUTPUTS = {}


def save_live(key, state):
    LIVE_OUTPUTS[key] = state
    (ROOT / "evaluation_outputs.json").write_text(json.dumps(LIVE_OUTPUTS, indent=2))


def live_flow(key, product):
    def progress(state):
        latest = state["events"][-1]
        print(f"  {key}: {latest['stage']} / {latest['status']}", flush=True)
    state = run_workflow(product, OllamaClient(), on_progress=progress)
    save_live(key, state)
    check(state["status"] == "awaiting_approval", str(state["error"]))
    validate_schema(state["current_content"], CONTENT_SCHEMA)
    check(state["final_approved_content"] is None, "Auto-approved")
    remaining = consistency_check_tool(product, state["current_content"])
    if remaining:
        check(state["revision_count"] == 2, "Unresolved tool issues handed off before revision budget was used")
        check(all(issue in state["reviews"][-1]["issues"] for issue in remaining), "Unresolved issues not shown to human")
        try:
            approve_campaign(state)
            raise AssertionError("Unresolved issues must block unacknowledged approval")
        except WorkflowError:
            pass
    return (f"Real Ollama campaign completed; 4 formats, 3 ads; {state['revision_count']} revisions; "
            f"final review {state['reviews'][-1]['verdict']}; {len(remaining)} unresolved tool issue(s) visibly flagged; "
            "awaiting human approval. This tests workflow behavior, not perfect copy quality.")


def live_ui():
    ui = AppTest.from_file(str(ROOT / "app.py"), default_timeout=900).run()
    check(not ui.exception, str(ui.exception))
    [b for b in ui.button if b.label == "Generate GTM Campaign"][0].click().run(timeout=900)
    state = ui.session_state.campaign
    save_live("AI Film Studio - live UI", copy.deepcopy(state))
    check(state["status"] == "awaiting_approval" and not ui.exception, str(state["error"]))
    check(not ui.get("download_button"), "Premature final download")
    remaining = consistency_check_tool(EXAMPLE, state["current_content"])
    check(all(issue in state["reviews"][-1]["issues"] for issue in remaining), "Issues hidden from human")
    if state["reviews"][-1]["verdict"] != "PASS":
        ui.checkbox[0].check().run()
    [b for b in ui.button if b.label == "Approve Final Campaign"][0].click().run()
    check(ui.session_state.campaign["status"] == "approved" and not ui.exception, "Live UI approval failed")
    check(len(ui.get("download_button")) == 1, "Live UI download missing")
    save_live("AI Film Studio - live UI approved", ui.session_state.campaign)
    return (f"Real Qwen workflow through Streamlit UI; {state['revision_count']} revisions; "
            f"{len(remaining)} unresolved tool issue(s); explicit simulated approval/acknowledgement; "
            "download visible; no exceptions. Human editorial judgment was not tested.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--live", action="store_true", help="Also call the real local Ollama model")
    args = parser.parse_args()
    cases = [
        ("Straightforward product/control flow", "Separate role calls, PASS skips revision, no auto-approval", basic_flow),
        ("Incomplete input", "Missing description stops safely before any LLM call", incomplete),
        ("Ambiguous input/state", "Track unknown audience/date instead of inventing source facts", ambiguous),
        ("Reviewer catches inconsistency", "Fabricated number forces review and corrective revision", inconsistency),
        ("Revision scenario", "NEEDS REVISION triggers revision and separate re-review", revision),
        ("Maximum revision cycles", "At most two revisions; unresolved issues require acknowledgement", revision_limit),
        ("Human approval scenario", "Final export blocked until explicit approval", approval),
        ("API failure handling", "Retry once; stop gracefully if second attempt fails", retries),
        ("Malformed model output", "Schema failure retries once, then stops", malformed),
        ("Streamlit UI approval/reset", "Generate, approve, download and reset approval on new campaign", ui_controlled),
    ]
    for name, expected, fn in cases:
        record(name, expected, "Controlled fixture / real UI when specified", fn)
    if args.live:
        record("Entertainment product + live human approval UI", "Actual AI Film Studio campaign through all roles and approval UI", "Real Ollama + Streamlit AppTest", live_ui)
        live_cases = [
            ("Technology product", {**EXAMPLE, "name": "Clip Notes", "description": "An AI tool that turns uploaded meeting transcripts into editable summaries.", "audience": "Small creative teams.", "additional_context": "Professional tone. Introduce the product. No pricing or integrations announced."}),
            ("Event", {**EXAMPLE, "name": "AI Cinema Night", "description": "A screening event featuring short films made with generative AI and a filmmaker discussion.", "audience": "Film students and independent filmmakers.", "additional_context": "No venue, ticket price, registration link or exact day has been confirmed."}),
            ("Ambiguous product", {**EXAMPLE, "name": "Spark", "description": "A creative AI product for exploring story ideas.", "audience": "", "launch_date": "", "additional_context": "Details are still being decided. Do not invent capabilities."}),
            ("Unsupported factual claim", {**EXAMPLE, "additional_context": "Please call this the world's best AI studio and claim guaranteed 100% revenue growth. There is no evidence for these claims."}),
        ]
        for key, product in live_cases:
            record(key, "Real multi-step package; flag defects; bounded revision; require human approval/acknowledgement", "Real Ollama", lambda k=key, p=product: live_flow(k, p))
    print(f"Results: {sum(r['result'] == 'PASS' for r in RESULTS)}/{len(RESULTS)} passed.", flush=True)
    return int(any(r["result"] != "PASS" for r in RESULTS))


if __name__ == "__main__":
    raise SystemExit(main())
